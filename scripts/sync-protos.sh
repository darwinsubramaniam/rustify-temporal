#!/usr/bin/env bash
# Keep rustify-temporal on exactly the same contract as the Go Temporal server.
#
# Copies into proto/:
#   - the public API (temporal/api, google, nexusannotations) at the exact version the Go server
#     pins in its go.mod (go.temporal.io/api vX -> temporalio/api-go vX -> its proto/api commit);
#   - the Go server's internal protos (proto/internal/temporal/server/...) from its source tree.
# and records where they came from in proto/VERSION.
#
#   scripts/sync-protos.sh            update proto/ from the Go server
#   scripts/sync-protos.sh --check    exit 1 if proto/ differs from the Go server's contract
#
# TEMPORAL_SRC=/path/to/temporal picks the Go server source (default: ../temporal).
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$PWD"
MODE="${1:-sync}"
TEMPORAL_SRC="${TEMPORAL_SRC:-$(cd "$ROOT/../temporal" && pwd)}"

API_VERSION=$(awk '$1 == "go.temporal.io/api" { print $2; exit }' "$TEMPORAL_SRC/go.mod")
[ -n "$API_VERSION" ] || { echo "go.temporal.io/api not found in $TEMPORAL_SRC/go.mod"; exit 1; }
# The last upstream commit that changed the contract (protos or the pinned API version), so CI can
# check out the same Go server source from GitHub.
SERVER_COMMIT=$(git -C "$TEMPORAL_SRC" log -1 --format=%H -- proto go.mod 2>/dev/null || echo unknown)

WORK=$(mktemp -d /tmp/rustify-protos.XXXXXX)
trap 'rm -rf "$WORK"' EXIT

git clone -q --depth 1 --branch "$API_VERSION" https://github.com/temporalio/api-go "$WORK/api-go" 2>/dev/null
API_COMMIT=$(git -C "$WORK/api-go" ls-tree HEAD proto/api | awk '{ print $3 }')
git init -q "$WORK/api"
git -C "$WORK/api" fetch -q --depth 1 https://github.com/temporalio/api "$API_COMMIT"
git -C "$WORK/api" checkout -q FETCH_HEAD

NEW="$WORK/proto"
mkdir -p "$NEW/internal"
cp -R "$WORK/api/temporal" "$WORK/api/google" "$WORK/api/nexusannotations" "$NEW/"
cp "$WORK/api/LICENSE" "$NEW/LICENSE-temporal-api"
cp -R "$TEMPORAL_SRC/proto/internal/temporal" "$NEW/internal/"
cp "$TEMPORAL_SRC/LICENSE" "$NEW/LICENSE-temporal-server"
cat > "$NEW/VERSION" <<EOF
# Generated by scripts/sync-protos.sh - do not edit.
# Public API: what the Go server pins (go.temporal.io/api) and the temporalio/api commit behind it.
go.temporal.io/api $API_VERSION
temporalio/api $API_COMMIT
# Internal protos: the last temporalio/temporal commit that changed them (or the pinned API version).
temporalio/temporal $SERVER_COMMIT
EOF

if [ "$MODE" = "--check" ]; then
  if diff -rq "$NEW" "$ROOT/proto" >"$WORK/diff.txt"; then
    echo "proto/ matches the Go server's contract (go.temporal.io/api $API_VERSION, temporalio/api ${API_COMMIT:0:12})."
  else
    echo "proto/ has drifted from the Go server's contract:"
    sed 's#'"$NEW"'#go-server#; s#'"$ROOT"'/##' "$WORK/diff.txt"
    echo "Run scripts/sync-protos.sh to update."
    exit 1
  fi
else
  rm -rf "$ROOT/proto"
  cp -R "$NEW" "$ROOT/proto"
  echo "proto/ synced: go.temporal.io/api $API_VERSION (temporalio/api ${API_COMMIT:0:12}), internal protos from temporal ${SERVER_COMMIT:0:12}."
fi
